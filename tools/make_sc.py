#!/usr/bin/env python3
"""由繁體正本 js/c-tc.js 產生簡體 js/c-sc.js。
用法:python3 tools/make_sc.py <repo 根目錄>   (需要 pip install opencc-python-reimplemented)
做法:OpenCC 繁轉簡,再按 v2.5 已批簡體版的用語調整(引號、年級名稱、披萨 / 块 / 换组 等),題目情境內的 $ 保留。
簡體用語如要修改,請改本檔的 TERMS,不要直接改 c-sc.js。"""
import re,sys,os
from opencc import OpenCC
root=sys.argv[1]
s=open(os.path.join(root,'js','c-tc.js'),encoding='utf-8').read()
s=OpenCC('t2s').convert(s)
TERMS=[
 ('「','“'),('」','”'),('『','‘'),('』','’'),
 ('甚么','什么'),('拣','选'),('帐号','账号'),('纪录','记录'),('这部装置','这台设备'),('装置','设备'),('资讯','信息'),
 ('投影片','幻灯片'),('上载','上传'),('相片','照片'),('手提电脑','笔记本电脑'),('计算机','计算器'),('智能手机','智能手机'),
 # 示範題(按 v2.5 已批簡體版)
 ('班会派对','班级派对'),('班会最多','班级最多'),('薄饼','披萨'),('交接','换组'),('几时要改','什么时候要改'),('小食','小吃'),('去不到','去不了'),
 ('放得进限制','符合限制'),('放不放得进限制','符不符合限制'),('放得进 ____','没有超过 ____'),('计对','算对'),('计出','算出'),('计完','算完'),('来计。','来算。'),
 ('总件数','总块数'),('多少件','多少块'),('两条示范题','两道示范题'),('条示范题','道示范题'),('这条题','这道题'),('一条情境题','一道情境题'),('一条你未做过','一道你未做过'),
 # 年級及學段(按 v2.5 已批簡體版:低 / 中 / 高年级)
 ('小三至小四','三至四年级'),('小三至小六','三至六年级'),('小三或以上','三年级或以上'),('按小四程度','按四年级程度'),
 ('初小组','低年级组'),('中小组','中年级组'),('高小组','高年级组'),('“高小”','“高年级”'),('四个程度','四个年级段'),
 ('初小','低年级'),
 # v3.0 最终优化:机械猫「数字生命」用语
 ('踢波','踢球'),('早晨！','早上好！'),('温了书','复习了功课'),('这里开始','这里开始'),
]
for a,b in TERMS: s=s.replace(a,b)
s=re.sub(r'([0-9_]) ?件(?![事物])',r'\1 块',s)            # 披萨的「件」
# 金額:題目情境(引用題目原句)保留 $,說明文字用「元」
out=[]
for line in s.split('\n'):
    keep=('4B 班有 30 位同学和 3 位老师' in line) or ('= 港元' in line) or ('“班级最多可用 $800。”' in line)
    out.append(line if keep else re.sub(r'\$\s?([0-9][0-9,]*)',r'\1 元',line))
s='\n'.join(out)
# 年級名稱及學段名稱
s=re.sub(r"grades: \{[^}]*\}","grades: { P1: '一年级', P2: '二年级', P3: '三年级', P4: '四年级', P5: '五年级', P6: '六年级', S1: '初一', S2: '初二', S3: '初三', S4: '高一', S5: '高二', S6: '高三', U: '大学组' }",s,count=1)
s=re.sub(r"stages: \{[^}]*\}","stages: { p12: '低年级', p34: '中年级', p56: '高年级', s13: '初中', s46: '高中', u: '大学组' }",s,count=1)
s=s.replace('window.PF_C.tc = {','window.PF_C.sc = {',1)
s=re.sub(r'/\*.*?\*/','/* 三赛道自学培训网站 v3.0 · 内容(简体中文)。本档由 tools/make_sc.py 从 js/c-tc.js 产生,请勿直接修改。 */',s,count=1,flags=re.S)
open(os.path.join(root,'js','c-sc.js'),'w',encoding='utf-8').write(s)
print('c-sc.js',len(s.encode()),'bytes')
